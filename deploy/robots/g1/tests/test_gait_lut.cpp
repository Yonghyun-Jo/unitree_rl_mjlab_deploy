int main() {
    chk(GL_STANCE_Z, 0.066877f, "STANCE_Z");

    // foot_z / stride_freq 격자 대조
    for (const auto& k : CASES) {
        float zl = 0.f, zr = 0.f;
        gl_foot_z(k.phase, k.eff, k.is_run != 0, zl, zr);
        char buf[96];
        std::snprintf(buf, sizeof buf, "foot_z zl ph=%.3f v=%.2f run=%d", k.phase, k.eff, k.is_run);
        chk(zl, k.zl, buf);
        std::snprintf(buf, sizeof buf, "foot_z zr ph=%.3f v=%.2f run=%d", k.phase, k.eff, k.is_run);
        chk(zr, k.zr, buf);
        std::snprintf(buf, sizeof buf, "stride_freq v=%.2f run=%d", k.eff, k.is_run);
        chk(gl_stride_freq(k.eff, k.is_run != 0), k.f, buf);
    }

    // walk<->run 히스테리시스 시퀀스 (walk_max 1.2 / run_min 1.7)
    bool is_run = false;
    for (const auto& g : SEQ) {
        is_run = gl_select_gait(g.eff, is_run, 1.2f, 1.7f);
        if (is_run != (g.is_run != 0)) {
            std::printf("FAIL select_gait eff=%.2f: got %d want %d\n", g.eff, (int)is_run, g.is_run);
            ++fail;
        }
    }

    if (fail) { std::printf("[test_gait_lut] %d FAIL\n", fail); return 1; }
    std::printf("[test_gait_lut] ALL PASS (%zu cases, %zu gait steps)\n",
                sizeof(CASES)/sizeof(CASES[0]), sizeof(SEQ)/sizeof(SEQ[0]));
    return 0;
}
