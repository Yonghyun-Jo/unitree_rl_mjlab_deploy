static void run_mode(int mode, const float want[][5]) {
    MaskedLocoController c;
    // deploy.yaml 의 gait 블록이 싣는 것과 같은 값
    c.mode_gait[1] = {true,  1.0f, GL_STANCE_Z, 0.0f};
    c.mode_gait[2] = {false, 1.2f, 0.066f,      0.15f};
    for (int i = 0; i < N; ++i) {
        c.update({SEQ[i][0], SEQ[i][1], SEQ[i][2]}, mode);
        char buf[64];
        std::snprintf(buf, sizeof buf, "mode%d base_vel.x", mode); chk(c.base_vel[0], want[i][0], buf, i);
        std::snprintf(buf, sizeof buf, "mode%d base_vel.y", mode); chk(c.base_vel[1], want[i][1], buf, i);
        std::snprintf(buf, sizeof buf, "mode%d base_vel.z", mode); chk(c.base_vel[2], want[i][2], buf, i);
        std::snprintf(buf, sizeof buf, "mode%d foot_z.L",   mode); chk(c.foot_z[0],  want[i][3], buf, i);
        std::snprintf(buf, sizeof buf, "mode%d foot_z.R",   mode); chk(c.foot_z[1],  want[i][4], buf, i);
    }
}

int main() {
    run_mode(1, WANT1);
    run_mode(2, WANT2);
    if (fail) { std::printf("[test_loco_gait_modes] %d FAIL\n", fail); return 1; }
    std::printf("[test_loco_gait_modes] ALL PASS (%d steps x 2 modes)\n", N);
    return 0;
}
