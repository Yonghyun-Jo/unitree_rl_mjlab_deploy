static int fail = 0;

static void chk(float got, float want, const char* what, float tol = 2e-6f)
{
    if (!(std::fabs(got - want) <= tol)) {
        std::printf("FAIL %s: got %.7f want %.7f (d=%.2e)\n", what, got, want,
                    std::fabs(got - want));
        ++fail;
    }
}

static void chk_true(bool c, const char* what)
{
    std::printf("  %s %s\n", c ? "ok  " : "FAIL", what);
    if (!c) ++fail;
}

